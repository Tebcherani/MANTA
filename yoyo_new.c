/*-----------------------------------------------------------------------*
  Layered Control master routines

  This file contains the master routine which calls the behaviors.  It also
  includes "resolve" which takes the commands generated by the active
  behaviors and arbitrates the commands to one final output command to the
  dynamic controller.  Finally, it includes the behaviors which can be
  called from the behavior library.

  J. G. Bellingham  12/18/93
 *-----------------------------------------------------------------------*/

