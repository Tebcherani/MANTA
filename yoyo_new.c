/*----------------------------------------------------------------------
  MANAGE_TIME:  J. G. Bellingham, 3-Mar-1994  

  This function is used by behaviors which have a time-out variable.  It
  returns 1 if a time-out has occured, otherwise it returns 0.

  jleonard 11/3/94 changed to take a pointer to a behavior, still need to
  remove the "int behavior" argument that indexes time_done[] and
  prev_state[], how can I do this?  should we force the behavior to keep
  these values in its argument list ?
  -----------------------------------------------------------------------*/

int manage_time( struct behavior *b, double duration )
{
                                /* if first call for this behavior, set
                                   start_time and end_time */
    if ( b->start_time < 0.0 )
    {
        b->start_time = sensor( M_PRESENT_TIME );
        b->end_time = sensor(M_PRESENT_TIME) + duration;
        sprintf( msg_buf, "% 8.2f: %s starts (end time %.2f)\n",
                 sensor(M_PRESENT_TIME), b->name, b->end_time );
        write_message( MonitorLayeredControl | SLOG );
    }

    if ( sensor(M_PRESENT_TIME) > b->end_time )
    {
        sprintf( msg_buf, "% 8.2f: %s managed time expired\n",
                 sensor(M_PRESENT_TIME), b->name );
        write_message( MonitorLayeredControl | SLOG );
        return 1;
    }
    return 0;                   /* behavior has not yet completed */
}

int stack_busy( struct command *cmd )
{
    return (cmd->speed_mode != -1) && (cmd->heading_mode != -1) &&
        (cmd->depth_mode != -1);
}

  
/*-------------------------------------------------------------------------- 
  SHUT_DOWN: Sets the command modes to -1 (null command) and sets vehicle
  stop variable to 1.

  J. G. Bellingham, 3/10/94                                                
 --------------------------------------------------------------------------*/

int shut_down( int priority )
{
    vvp->c[priority].heading_mode = -1;
    vvp->c[priority].depth_mode = -1;
    vvp->c[priority].speed_mode = -1;
}

