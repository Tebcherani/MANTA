"""
extract_missions.py

Scan a directory containing Odyssey *.odb files, extract the embedded
mission-script ASCII header from each file, and write it out as:

    example.odb  ->  example.mi

The generated mission file begins with a comment summarizing:
- source ODB filename
- detected mission runtime
- extraction timestamp
"""

from __future__ import annotations

import argparse
import datetime as dt
import pathlib
import re
from typing import Optional

print("RUNNING EXTRACT_MISSIONS FROM:", __file__)

MISSION_START_PATTERNS = [
    re.compile(rb"^UseSim", re.MULTILINE),
    re.compile(rb"^behavior:", re.MULTILINE),
    re.compile(rb"^sensor:", re.MULTILINE),
]


MISSION_END_PATTERNS = [
    re.compile(rb"^\d+\s+[A-Za-z_]", re.MULTILINE),
]


RUNTIME_PATTERNS = [
    re.compile(rb"mission elapsed time[^\d]*([\d\.]+)", re.IGNORECASE),
    re.compile(rb"mission time[^\d]*([\d\.]+)", re.IGNORECASE),
    re.compile(rb"elapsed[^\d]*([\d\.]+)", re.IGNORECASE),
]


def read_ascii_header(path: pathlib.Path,
                      max_bytes: int = 1024 * 1024) -> str:
    """
    Read the ASCII portion of the ODB file.
    """

    with path.open("rb") as f:
        raw = f.read(max_bytes)

    return raw.decode("utf-8", errors="ignore")


def extract_runtime(header_text: str) -> Optional[float]:
    """
    Attempt to detect mission runtime in seconds.
    """

    raw = header_text.encode("utf-8", errors="ignore")

    for pat in RUNTIME_PATTERNS:
        m = pat.search(raw)
        if m:
            try:
                return float(m.group(1).decode())
            except Exception:
                pass

    return None


def extract_mission_text(header_text: str) -> Optional[str]:
    """
    Locate the embedded mission script inside the ODB ASCII header.
    """

    raw = header_text.encode("utf-8", errors="ignore")

    start_idx = None

    for pat in MISSION_START_PATTERNS:
        m = pat.search(raw)
        if m:
            idx = m.start()
            if start_idx is None or idx < start_idx:
                start_idx = idx

    if start_idx is None:
        return None

    end_idx = len(raw)

    for pat in MISSION_END_PATTERNS:
        m = pat.search(raw, start_idx)
        if m and m.start() > start_idx:
            end_idx = min(end_idx, m.start())

    mission_raw = raw[start_idx:end_idx]

    mission_text = mission_raw.decode("utf-8", errors="ignore")

    mission_text = re.sub(r"\n{3,}", "\n\n", mission_text)

    return mission_text.strip() + "\n"


def write_mission_file(
    odb_path: pathlib.Path,
    mission_text: str,
    runtime_seconds: Optional[float],
) -> pathlib.Path:
    """
    Write extracted mission to sibling .mi file.
    """

    mi_path = odb_path.with_suffix(".mi")

    timestamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    if runtime_seconds is not None:
        runtime_str = f"{runtime_seconds:.1f} s"
    else:
        runtime_str = "unknown"

    header = (
        f"# Extracted from {odb_path.name}\n"
        f"# Actual mission runtime: {runtime_str}\n"
        f"# Extraction timestamp: {timestamp}\n"
        f"# Generated by SUtilities/extract_missions.py\n\n"
    )

    with mi_path.open("w", newline="\n") as f:
        f.write(header)
        f.write(mission_text)

    return mi_path


def process_odb(odb_path: pathlib.Path) -> None:
    print(f"Processing {odb_path.name} ...")

    try:
        header_text = read_ascii_header(odb_path)

        mission_text = extract_mission_text(header_text)

        if not mission_text:
            print("  WARNING: Could not locate mission text")
            return

        runtime_seconds = extract_runtime(header_text)

        out_path = write_mission_file(
            odb_path,
            mission_text,
            runtime_seconds,
        )

        print(f"  Wrote {out_path.name}")

    except Exception as e:
        print(f"  ERROR: {e}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Extract embedded mission scripts from Odyssey ODB files"
    )

    parser.add_argument(
        "directory",
        type=pathlib.Path,
        help="Directory containing *.odb files",
    )

    args = parser.parse_args()

    print("DIRECTORY ARG:", args.directory)
    print("DIRECTORY TYPE:", type(args.directory))
    print("DIRECTORY EXISTS:", args.directory.exists())
    print("DIRECTORY IS DIR:", args.directory.is_dir())

    if not args.directory.exists():
        print(f"ERROR: directory does not exist: {args.directory}")
        return 1

    import os

    search_root = str(args.directory)

    print("SEARCH ROOT:", search_root)

    odb_files = []

    for root, dirs, files in os.walk(search_root):

        print("ROOT:", root)

        for fname in files:

            print("FILE:", fname)

            if ".obd" in fname.lower():

                print("MATCH:", fname)

                full_path = pathlib.Path(root) / fname

                odb_files.append(full_path)

    odb_files.sort()

    print(f"DEBUG: found {len(odb_files)} candidate ODB files")

    if not odb_files:
        print("No .odb files found")
        return 1

    print(f"Found {len(odb_files)} ODB files")

    for odb_path in odb_files:
        process_odb(odb_path)

    print("Done")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
