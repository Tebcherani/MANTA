int stack_busy( struct command *cmd );
int getXSDataByte( void );
static int behavior_axis_mask( int behavior_id );

#define AXIS_DEPTH   1
#define AXIS_HEADING 2
#define AXIS_SPEED   4

/*----------------------------------------------------------------------*
  LAYERED_CONTROL

  This is the layered control execution and resolution routine.

  J. G. Bellingham
 *----------------------------------------------------------------------*/


void layered_control( void )
{
    register struct behavior *b;
    register int priority, j;
    struct command *cmd;
    int behavior_id, status, mask;
    int depth_priority = -1, heading_priority = -1, speed_priority = -1;
    int depth_behavior = -1, heading_behavior = -1, speed_behavior = -1;
    int state_before, command_changed;
    int depth_mode_before, heading_mode_before, speed_mode_before;
    double depth_before[MAX_C_ARG], heading_before[MAX_C_ARG];
    double speed_before[MAX_C_ARG];

/* Start with low priority behaviors and work to high priority,
   i.e., start at the high end of the structure and work down. */

    for ( priority = MAX_COMMAND - 1; priority > 0; priority-- )

        if ( vvp->sta[vvp->cstate].c[priority].behavior != -1 )
	{
	    behavior_id = vvp->sta[vvp->cstate].c[priority].behavior;
	    b = &vvp->sta[vvp->cstate].c[priority].b;

	    if ( (b->state == B_ACTIVE) || (b->state == B_UNINITIALIZED) )
	    {
		if (b->fcn != NULL)
		{
				/* resolve command stack from lower
				   priority to this level */
		    resolve( priority );
		    cmd = &vvp->c[priority];
		    state_before = b->state;
		    depth_mode_before = cmd->depth_mode;
		    heading_mode_before = cmd->heading_mode;
		    speed_mode_before = cmd->speed_mode;
		    for ( j = 0; j < MAX_C_ARG; j++ )
		    {
			depth_before[j] = cmd->depth[j];
			heading_before[j] = cmd->heading[j];
			speed_before[j] = cmd->speed[j];
		    }
				/* call the behavior */
		    status = b->fcn( b, priority, 0 );

		    command_changed =
			(cmd->depth_mode != depth_mode_before) ||
			(cmd->heading_mode != heading_mode_before) ||
			(cmd->speed_mode != speed_mode_before);
		    for ( j = 0; j < MAX_C_ARG; j++ )
		    {
			if ( (cmd->depth[j] != depth_before[j]) ||
			     (cmd->heading[j] != heading_before[j]) ||
			     (cmd->speed[j] != speed_before[j]) )
			    command_changed = 1;
		    }

		    if ( (status != -1) &&
			 (command_changed || state_before == B_ACTIVE ||
			  b->state == B_ACTIVE) )
		    {
			mask = behavior_axis_mask( behavior_id );
			if ( (mask & AXIS_DEPTH) && (cmd->depth_mode != -1) )
			{
			    depth_priority = priority;
			    depth_behavior = behavior_id;
			}
			if ( (mask & AXIS_HEADING) && (cmd->heading_mode != -1) )
			{
			    heading_priority = priority;
			    heading_behavior = behavior_id;
			}
			if ( (mask & AXIS_SPEED) && (cmd->speed_mode != -1) )
			{
			    speed_priority = priority;
			    speed_behavior = behavior_id;
			}
		    }
		}
		else
		{
		    sprintf( msg_buf, "% 8.2f: layered_control has NULL "
			     "function ptr\n", sensor(M_PRESENT_TIME) );
		    write_message( TERM | SLOG );
		}
	    }
        }
				/* Load output command for dynamic
				   controller */
    resolve( 0 );
				/* Store generated commands in sensor
				   structure for replay */
    update( CC_HEADING_MODE, vvp->c[0].heading_mode );
    update( CC_DEPTH_MODE, vvp->c[0].depth_mode );
    update( CC_SPEED_MODE, vvp->c[0].speed_mode );
    update( C_DEPTH_BEHAVIOR, depth_behavior );
    update( C_DEPTH_PRIORITY, depth_priority );
    update( C_HEADING_BEHAVIOR, heading_behavior );
    update( C_HEADING_PRIORITY, heading_priority );
    update( C_SPEED_BEHAVIOR, speed_behavior );
    update( C_SPEED_PRIORITY, speed_priority );
}

/*----------------------------------------------------------------------*
  RESOLVE:

  This routine resolves the commands in the command structure.  It looks
  at the command from the last behavior to run, and carries it down to
  the level (pres_priority) at which this function has been called.

  Truth be told, this function doesn't resolve anything, it simply
  carries the command generated by lower priority behaviors to the
  present level then lets the called behavior decide what to do (it can
  see the commands generated by the higher level routines because they
  have been written into this functions outputs).

  The depth_mode, speed_mode, and heading_mode variable indicates what
  type of command has been generated by the behaviors and is being
  passed to the controller.  If this variable is -1, NO COMMAND IS
  GENERATED.  The zero level of the command structure, i.e.,
  c[0].speed_mode, is the level which is read by the dynamic controller.

  J. G. Bellingham 2/1/94
 *----------------------------------------------------------------------*/

void resolve( int pres )
{
    register struct command *cmd = &vvp->c[pres];
    int i;
    static int last = 0;

/* if last call to this function had higher priority (lower number) than
   this call, we're at the top of the stack and need to initialize the
   modes to -1 */

    if ( last < pres )
    {
	cmd->depth_mode = -1;
	cmd->speed_mode = -1;
	cmd->heading_mode = -1;
	vvp->c[0].depth_mode = -1;
	vvp->c[0].speed_mode = -1;
	vvp->c[0].heading_mode = -1;
	last = pres;   
    }
				/* resolve commands to this level */
   cmd->depth_mode = vvp->c[last].depth_mode;
   cmd->heading_mode = vvp->c[last].heading_mode;
   cmd->speed_mode = vvp->c[last].speed_mode;
   for ( i = 0; i < MAX_C_ARG; i++ )
   {
       cmd->depth[i] = vvp->c[last].depth[i];
       cmd->heading[i] = vvp->c[last].heading[i];
       cmd->speed[i] = vvp->c[last].speed[i];
   }
   last = pres;   
}

static int behavior_axis_mask( int behavior_id )
{
    switch ( behavior_id )
    {
    case ACQUIRE_HEADING:
	return AXIS_HEADING;
    case ASCEND:
    case DESCEND:
    case DOCK:
    case UNDOCK:
    case WHOI_HOMING:
    case EDC_HOMING:
    case SET_ELEVATOR:
    case SET_RUDDER:
    case SETPOINT:
    case SETVECTOR:
    case SURVEY_DEAD_RECKON:
    case WAYPOINT_2D:
    case WIGGLE:
    case LAUNCH:
	return AXIS_DEPTH | AXIS_HEADING | AXIS_SPEED;
    case YO_YO:
	return AXIS_DEPTH;
    case CHIRP_FIN:
	return AXIS_DEPTH | AXIS_HEADING;
    case SETMODE:
	return AXIS_DEPTH | AXIS_HEADING | AXIS_SPEED;
    default:
	return 0;
    }
}

/*-----------------------------------------------------------------------*

behavior: descend
  b_arg:                   heading(rad) 0
  b_arg:              rudder_angle(rad) 0
  b_arg:             descent_angle(rad) 0
  b_arg:                     speed(m/s) 0
  b_arg:                   end_depth(m) 0
  b_arg:                min_altitude(m) 0
  b_arg:      drop_descent_weight(bool) 0
  b_arg:       drop_ascent_weight(bool) 0
  b_arg:                    max_time(s) 0
 *-----------------------------------------------------------------------*/

int descend(struct behavior *b, int priority, int level)
{
    register struct command *cmd = &vvp->c[priority];
    enum { HEADING, RUDDER, PITCH, SPEED, DEPTH, MIN_ALT, DROPD, DROPA,
	   MAX_TIME };

    if ( stack_busy(cmd) )
	return -1;
				/* If end conditions occur, drop drop
                                   weights, set end_depth to < 0 */
    if ( (manage_time(b, bArg(MAX_TIME)) == 1) || 
	 (sensor(M_DEPTH) > bArg(DEPTH)) ||
	 ((sensor(M_ALTITUDE) > 0.0) && (sensor(M_ALTITUDE) < bArg(MIN_ALT))) )
    {
	if (bArg(DROPD) > 0)
	{
	    update( C_WEIGHT1_DROP, 1.0 );
	    fprintf( syslog, "% 8.2f: %s dropping descent weight\n",
		     sensor(M_PRESENT_TIME), b->name );
	}
    	if (bArg(DROPA) > 0)
	{
	    update( C_WEIGHT2_DROP, 1.0 );
	    fprintf( syslog, "% 8.2f: %s dropping ascent weight\n",
		     sensor(M_PRESENT_TIME), b->name );
	}
	b->state = B_COMPLETE;
	return 0;
    }
				/* choose between direct rudder angle or
				   heading control */
    if ( fabs(bArg(RUDDER)) > 1e-6 )
    {
	vvp->c[priority].heading_mode = 0;
	vvp->c[priority].heading[0] = bArg(RUDDER);
    }
    else  
    {
	vvp->c[priority].heading_mode = 1;
	vvp->c[priority].heading[0] = bArg(HEADING);
    }
				/* Load pitch */
    vvp->c[priority].depth_mode = 2;
    vvp->c[priority].depth[0] = -fabs(bArg(PITCH));
				/* Load speed */
    vvp->c[priority].speed_mode = 1;
    vvp->c[priority].speed[0] = bArg(SPEED);
    return 1;
}

/*----------------------------------------------------------------------*
  ASCEND: Revised B. A. Moran, 27-Sep-1997

  Drive the vehicle to to the surface by dropping either, neither, or both
  of the drop weights and then terminate.  Vertical plane mode 2 is used,
  i.e., pitch control.

  Heading control is used if |rudder_angle| < 1e-6, otherwise the vehicle
  will spiral with fixed rudder.

  Terminate when the vehicle is above the end_depth.
 
  behavior: ascend  2
    b_arg:                   heading(rad) 0
    b_arg:              rudder_angle(rad) 0
    b_arg:              ascent_angle(rad) 0
    b_arg:                     speed(m/s) 0
    b_arg:                   end_depth(m) 1
    b_arg:      drop_descent_weight(bool) 0
    b_arg:       drop_ascent_weight(bool) 0
    b_arg:     abort_mission_active(bool) 0
 *----------------------------------------------------------------------*/

int ascend( struct behavior *b, int priority, int level )
{
    register struct command *cmd = &vvp->c[priority];
    enum { HEADING, RUDDER, PITCH, SPEED, DEPTH, DROPD, DROPA, ABORT };
    int commandedAbort;
				/* decide if abort was issued */
    commandedAbort = (bArg(ABORT) > 0) && (sensor(C_ABORT_MISSION) > 0);

    if ( b->state == B_UNINITIALIZED )
    {
				/* stack busy and no abort issued? */
	if ( !commandedAbort && stack_busy(cmd) )
	    return -1;
				/* activate behavior, perform 1st time
				   through tasks */
	b->state = B_ACTIVE;
				/* drop descent weight? */
        if ( bArg(DROPD) > 0 )
	{
            update( C_WEIGHT1_DROP, 1 );
            fprintf( syslog, "% 8.2f: %s dropping descent weight\n",
		     sensor(M_PRESENT_TIME), b->name );
        }
				/* drop ascent weight? */
        if ( bArg(DROPA) > 0 )
	{
            update( C_WEIGHT2_DROP, 1 );
            fprintf( syslog, "% 8.2f: %s dropping ascent weight\n",
		     sensor(M_PRESENT_TIME), b->name );
        }
				/* abort? replace given arguments with 30
				   deg pitch spiral up */
	if ( commandedAbort )
	{
	    sprintf( msg_buf, "% 8.2f: %s activated by remote abort\n",
		     sensor(M_PRESENT_TIME), b->name );
	    write_message( MonitorLayeredControl | SLOG );
	    if ( fabs(bArg(RUDDER)) < 1e-6 )
		 bArg(RUDDER) = D2R(10);
	    bArg(PITCH) = D2R(30);
	}
    }
    if ( b->state == B_ACTIVE )
    {
				/* done if measured depth less than
				   end_depth */
	if ( sensor(M_DEPTH) < bArg(DEPTH) )
	{
	    b->state = B_COMPLETE;
	    sprintf( msg_buf, "% 8.2f: %s done (dpth %.2g < goal %.2g)\n", 
		     sensor(M_PRESENT_TIME), b->name, sensor(M_DEPTH),
		     bArg(DEPTH) );
	    write_message( MonitorLayeredControl | SLOG );
	    return 1;
	}
				/* choose between direct rudder angle or
				   heading control */
	if ( fabs(bArg(RUDDER)) > 1e-6 )
	{
	    vvp->c[priority].heading_mode = 0;
	    vvp->c[priority].heading[0] = bArg(RUDDER);
	}
	else  
	{
	    vvp->c[priority].heading_mode = 1;
	    vvp->c[priority].heading[0] = bArg(HEADING);
	}
				/* Load pitch */
	vvp->c[priority].depth_mode = 2;
	vvp->c[priority].depth[0] = bArg(PITCH);
				/* Load speed */
	vvp->c[priority].speed_mode = 1;
	vvp->c[priority].speed[0] = bArg(SPEED);
    }

    return 0;
}

/*-----------------------------------------------------------------------*
  BROADCAST: Used to send messages, initially through EdgeTech PS8000 XS
  command set and UAM channel, but in general through other means.

  Arguments control when activity begins, duration, and how often data is
  sent through the channel.

  B. A. Moran, 15-Dec-1997

  behavior: broadcast
    b_arg:                  start_time(s) 120
    b_arg:                    duration(s) 43200 (12 hr)
    b_arg:                    xs_delay(s) 120
    b_arg:                    xs_cycle(s) 120
    b_arg:                   uam_delay(s) 0
    b_arg:                   uam_cycle(s) 1
 *-----------------------------------------------------------------------*/

int broadcast( struct behavior *b, int priority, int level )
{
    enum { START, DURATION, XS_DELAY, XS_CYCLE, UAM_DELAY, UAM_CYCLE };

    switch ( b->state )
    {
				/* initialize behavior if present time is
				   greater than start time */
    case B_UNINITIALIZED:

	if ( bArg(START) > sensor(M_PRESENT_TIME) )
	    return -1;
				/* rereference delay args from nominal
				   start of behavior */
	bArg( UAM_DELAY ) += bArg( START );
	bArg( XS_DELAY )  += bArg( START );
	b->state = B_ACTIVE;
				/* "break" intentionally omitted */
    case B_ACTIVE:
				/* completed when duration has expired */
	if ( manage_time(b, bArg(DURATION)) == 1 )
	{
	    b->state = B_COMPLETE;
	    return 1;
	}
				/* use XS_DELAY argument as timer for
                                   EdgeTech data */
	if ( sensor(M_PRESENT_TIME) >= bArg(XS_DELAY) )
	{
				/* compose the databyte based on presence
				   of pole in latch */
#ifdef EDGEPS8000
	    update( EDGE_XS_DATABYTE, getXSDataByte() );

	    sprintf( msg_buf, "% 8.2f: %s to PS8000 XS (0x%02x)\n",
		     sensor(M_PRESENT_TIME), b->name,
		     (int) sensor(EDGE_XS_DATABYTE) );
	    write_message( MonitorLayeredControl );
#endif
				/* advance timer */
	    bArg( XS_DELAY ) += bArg( XS_CYCLE );
	}
				/* use UAM_DELAY argument as timer for UAM
				   data, advances similarly to above */
	if ( sensor(M_PRESENT_TIME) >= bArg(UAM_DELAY) )
	{
				/* compose simple message */
	    sprintf( vvp->modem_send, "%05d%04d%04d%03d%04d\xd",
		     (int) sensor(M_PRESENT_TIME),
		     (int) limit(sensor(M_POS_N), 9999, 0),
		     (int) limit(sensor(M_POS_E), 9999, 0),
		     (int) limit(sensor(M_DEPTH),  999, 0) );

	    sprintf( msg_buf, "% 8.2f: %s to UAM (%.*s)\n",
		     sensor(M_PRESENT_TIME), b->name,
		     strlen(vvp->modem_send) - 1, vvp->modem_send );
	    write_message( MonitorLayeredControl );
				/* advance timer */
	    bArg( UAM_DELAY ) += bArg( UAM_CYCLE );
	}
    }
    return 0;
}

/* -------------------------------------------------------------------------- 
|  YO_YO:                                                                  
|   This behavior causes the vehicle to move up and down between two
|   specified depth extremes (bottom_depth and top_depth).  If it gets too
|   close to the bottom (i.e. altimeter reading less than closest_approach)
|   then the vehicle will go into an ascent.
|
|   All vertical plane control is pitch control.  This behavior does not 
|   control either heading or speed, so some other behavior must handle
|   horizontal plane motion.
|
|   Termination occurs when either the vehicle has completed the requested
|   number of yo-yo cyles, or the behavior has run for max_time, which ever
|   comes first.  Note:  one complete cycle consists of both an up and down
|   motion.
|
|   If one wishes to disable the bottom triggered termination of a down leg
|   (say, because the altimeter is not working properly) then set the
|   variable min_altitude to a negative value.  
|  
|  Arguments are:
|    0    "desired_pitch(rad)", 0.000000, 0, 0, 
|    1    "top_depth(m)", 0.000000, 0, 0, 
|    2    "bottom_depth(m)", 0.000000, 0, 0, 
|    3    "min_altitude(m)", 0.000000, 0, 0, 
|    4    "cycles(int)", 0.000000, 0, 0, 
|    6    "max_time(s)", 0.000000, 0, 0, 
|
|  J. G. Bellingham, 7/11/94                                                
  -------------------------------------------------------------------------- */

int yo_yo( struct behavior *b, int priority, int level )
{
    register struct command *cmd = &vvp->c[priority];
    int companion_priority;
    struct command *companion_cmd;
    struct behavior *companion;

    companion_priority = priority + 1;
    if ( companion_priority >= MAX_COMMAND )
    {
	shut_down( priority );
	b->state = B_COMPLETE;
	sprintf( msg_buf, "% 8.2f: %s done (no companion priority)\n",
		 sensor(M_PRESENT_TIME), b->name );
	write_message( MonitorLayeredControl | SLOG );
	return 1;
    }

    companion_cmd = &vvp->c[companion_priority];
    companion = &vvp->sta[vvp->cstate].c[companion_priority].b;

    if ( b->state == B_UNINITIALIZED )
    {
	if ( (vvp->sta[vvp->cstate].c[companion_priority].behavior == -1) ||
	     (companion->state != B_ACTIVE) ||
	     (companion_cmd->heading_mode == -1) ||
	     (companion_cmd->speed_mode == -1) )
	    return -1;

	b->state = B_ACTIVE;
    }

				/* if behavior has timed out or all cycles
                                   complete, return 1 */
    if ( manage_time(b, bArg(5)) == 1 )
    {
	b->state = B_COMPLETE;
	return 1;
    }

    if ( (cmd->heading_mode == -1) || (cmd->speed_mode == -1) )
    {
	shut_down( priority );
	b->state = B_COMPLETE;
	sprintf( msg_buf, "% 8.2f: %s done (companion lost heading/speed)\n",
		 sensor(M_PRESENT_TIME), b->name );
	write_message( MonitorLayeredControl | SLOG );
	return 1;
    }

  /* jleonard 6/21/96 changing so that if number of cycles elapses, then we
     will set the modes to -1 to cause shut down of the vehicle unless
     another behavior up the stack takes control.  This means that you
     cannot do a long setpoint with a single cycle yoyo at the start with
     the yoyo then dropping out and the setpoint resuming control.  But I
     think this way is safer because of our altimeter problems
     (i.e. usually, we set # cycles to a very large value, and if we
     execute that many cycles, something has gone seriously wrong and we
     should end the mission. */

    if (b->arg[4].x < 0.25) { /* # of cycles has elapsed -- try to end mission */
	vvp->c[priority].depth_mode = -1;
	vvp->c[priority].speed_mode = -1;
	vvp->c[priority].heading_mode = -1;
	sprintf( msg_buf, "% 8.2f: %s shuts down on cycle count\n",
		 sensor(M_PRESENT_TIME), b->name );
	write_message( MonitorLayeredControl | SLOG );

	return 1;
    }
				/* Check to see if finished with an up leg
                                   of yo-yo */
    if ((sensor(M_DEPTH) < b->arg[1].x) && (b->arg[0].x > 0.0))
    {
	b->arg[0].x = -b->arg[0].x;
	b->arg[4].x = b->arg[4].x - 0.5;
        sprintf( msg_buf, "% 8.2f: %s up-leg ends at %.2f m\n",
		 sensor(M_PRESENT_TIME), b->name, sensor(M_DEPTH) );
        write_message( MonitorLayeredControl | SLOG );
    }
          
				/* Check to see if finished with a down leg
                                   of yo-yo */
    if ((sensor(M_DEPTH) > b->arg[2].x) && (b->arg[0].x < 0.0))
    {
	b->arg[0].x = -b->arg[0].x;
	b->arg[4].x = b->arg[4].x - 0.5;
        sprintf( msg_buf, "% 8.2f: %s down-leg ends at dpth %.2f m\n",
		 sensor(M_PRESENT_TIME), b->name, sensor(M_DEPTH) );
        write_message( MonitorLayeredControl | SLOG );
    }
				/* Check for near bottom termination of
                                   down leg of yo-yo */
  /* jleonard changing this to ignore zero ranges from the altimeter.
     this is dangerous because the sonar can return 0.0 if it is too
     close to an object;  however, generally, we would usually see 
     zero if a) the sonar was never interrogated (0.0 is inital value
     in the data structure) or b) the sonar is in air.  */

    if ((sensor(M_ALTITUDE) > 0.0) && (sensor(M_ALTITUDE) < b->arg[3].x) && 
	(b->arg[0].x < 0.0))
    {
	b->arg[0].x = -b->arg[0].x;
	b->arg[4].x = b->arg[4].x - 0.5;
        sprintf( msg_buf, "% 8.2f: %s down-leg ends at alt %.2f m, "
                "(dpth = %.2f m)\n", 
                sensor(M_PRESENT_TIME), b->name, sensor(M_ALTITUDE),
		 sensor(M_DEPTH) );
        write_message( MonitorLayeredControl | SLOG );
    }  
  
				/* set output command */
    cmd->depth_mode = 2;
    cmd->depth[0] = b->arg[0].x;    

    return(0);
}


/*-------------------------------------------------------------------------
  SURVEY_DEAD_RECKON: J. G. Bellingham, 3/94 (Rewritten to simplify leg
  calculations using remainder arithmetic, B. A. Moran 15-Sep-1997.)

  This behavior follows a successions of headings, sequenced in such a way
  as to provide a transit, then a grid survey type flight path.

 behavior: survey_dead_reckon
  b_arg:             trans_heading(rad) 0
  b_arg:                  trans_time(s) 0
  b_arg:              heading_leg1(rad) 0
  b_arg:                   time_leg1(s) 0
  b_arg:              heading_leg2(rad) 0
  b_arg:                   time_leg2(s) 0
  b_arg:                      cycles(#) 0
  b_arg:                       depth(m) 0
  b_arg:             transit_speed(m/s) 0
  b_arg:              survey_speed(m/s) 0

  -----------------------------------------------------------------------*/

int survey_dead_reckon( struct behavior *b, int priority, int level )
{
    register struct command *cmd = &vvp->c[priority];
    enum { T_HEAD, T_TIME, L1_HEAD, L1_TIME, L2_HEAD, L2_TIME, CYCLE,
	   DEPTH, T_SPEED, S_SPEED };
    double elapsed = 0, heading, speed, frac, period, ipart;

    switch ( b->state )
    {	
    case B_UNINITIALIZED:
				/* return immediately if stack busy */
	if ( stack_busy(cmd) )
	    return 0;
				/* otherwise, go active */
	b->state = B_ACTIVE;
				/* elapsed used here to calculate expected
				   time in this behavior for manage_time */
	elapsed = 2*bArg(CYCLE)*(bArg(L1_TIME) + bArg(L2_TIME)) -
	    bArg(L2_TIME) + bArg(T_TIME);

    case B_ACTIVE:

	if ( manage_time(b, elapsed) )
	{
	    b->state = B_COMPLETE;
	    return 1;
	}
				/* here on out, elapsed is how much time
				   has elapsed since end of transit portion */
	elapsed = sensor(M_PRESENT_TIME) - b->start_time - bArg(T_TIME);

				/* load output vector */
	cmd->depth_mode = cmd->heading_mode = cmd->speed_mode = 1;
				/* depth is straightforward */
	cmd->depth[0] = bArg( DEPTH );

				/* heading and speed depend on phase of
				   behavior */
	if ( elapsed < 0 )
	{
				/* negative elapsed implies transit */
	    cmd->heading[0] = bArg(T_HEAD);
	    cmd->speed[0] = bArg(T_SPEED);
	}
	else
	{
				/* speed always same in survey portion */
	    cmd->speed[0] = bArg(S_SPEED);
				/* use remainder arithmetic to determine
				   how many integral and fractional periods
				   of L1 + L2 have elapsed */
	    period = bArg(L1_TIME) + bArg(L2_TIME);
	    frac = period * modf( elapsed / period, &ipart );

	    if ( frac >= bArg(L1_TIME) )
				/* fractional part >= L1 implies on leg2 */
		cmd->heading[0] = bArg(L2_HEAD);

	    else
	    {
				/* integral part odd implies leg3, with
				   heading reciprocal of leg1 */
		if ( ((int) ipart) % 2 )
		    cmd->heading[0] = bArg(L1_HEAD) + PI;
		else
		    cmd->heading[0] = bArg(L1_HEAD);
	    }
	}
    } /* switch */
    return 0;
}


/*-----------------------------------------------------------------------*
  MISSION_TIMER: Shuts the vehicle down once the preset time has elapsed. 

  J. G. Bellingham 3/10/94, updated 05-Jan-1998, B. A. Moran

  behavior: mission_timer
    b_arg:                        time(s) 0
    b_arg:                autoterminate() 1
 *-----------------------------------------------------------------------*/

int mission_timer( struct behavior *b, int priority, int level )
{
				/* If behavior has timed out, return 1
				   after shutting vehicle down */
    if ( manage_time(b, bArg(0)) == 1 )
    {
	shut_down( priority );
	return 1;
    }
    return 0;
}

/* -------------------------------------------------------------------------- 
|  ACQUIRE_HEADING:                                                                  
|   This behavior turns the vehicle to the desired heading, without controlling
|    speed and depth.  Once it is within "acceptable_error" of the desired
|    heading it turns itself off.
|  
|  Arguments are:
|    0    "heading(rad)", 0.000000, 0, 0, 
|    1    "acceptable_error(rad)", 0.000000, 0, 0, 
|    2    "behavior_active(bool)", 0.000000, 0, 0, 
|                                                                            
|  J. G. Bellingham, 3/4/94
  -------------------------------------------------------------------------- */

int acquire_heading(struct behavior *b, int priority, int level)
{
  double heading, heading_err, active;
  
  heading = b->arg[0].x;
  heading_err = b->arg[1].x;
  active = b->arg[2].x;
  
  /*--- Check if behavior active flag is zero...return if it is */
  if (!(active > 0.0))
    return(1);

  /*--- If behavior succeeds, return 1 without generating any commands */
  if (fabs(wrap_angle(heading-sensor(M_YAW)))<heading_err)
    {

    b->arg[2].x = 0.0;
    return(1);  
    }
    
  /*--- Load the output commands... */
  vvp->c[priority].heading_mode = 1;
  vvp->c[priority].heading[0] = b->arg[0].x;    

  return(0); 
}

/* -------------------------------------------------------------------------- 
|  SETMODE:                                                                  
|   This behavior allows one to choose the mode of commands for heading, 
|                depth and speed and then set the command values.  It terminates on 
|                a timeout.    
|
|                vvp->c[0].heading_mode
|                        -1:        no heading command output by this behavior...
|           0:  vvp->c[0].heading[0] carries the desired rudder angle.
|           1:  vvp->c[0].heading[0] carries the desired heading
|                vvp->c[0].depth_mode
|                        -1:        no depth command output by this behavior...
|           0:  vvp->c[0].depth[0] carries the desired elevator angle.
|           1:  vvp->c[0].depth[0] carries the desired depth
|                        2:        vvp->c[0].depth[0] carries the desired pitch
|                                        (interpreted to mean pitch)
|                vvp->c[0].speed_mode
|                        -1:        no speed command output by this behavior...
|           0:  vvp->c[0].speed[0] carries the desired thruster amperage.
|           1:  vvp->c[0].speed[0] carries the desired vehicle speed (m/s),
|                                        control is open loop...
|
|  Arguments are:
|    0    "heading_mode(int)", 0.000000, 0, 0, 
|    1    "heading_commmand1(?)", 0.000000, 0, 0, 
|    2    "heading_commmand2(?)", 0.000000, 0, 0, 
|    3    "depth_mode(int)", 0.000000, 0, 0, 
|    4    "depth_commmand1(?)", 0.000000, 0, 0, 
|    5    "depth_commmand2(?)", 0.000000, 0, 0, 
|    6    "speed_mode(int)", 0.000000, 0, 0, 
|    7    "speed_commmand1(?)", 0.000000, 0, 0, 
|    8    "speed_commmand2(?)", 0.000000, 0, 0, 
|    9    "time(s)", 0.000000, 0, 0,                                     
|                                                                            
|  J. G. Bellingham, 1/22/95                                                
  -------------------------------------------------------------------------- */

int setmode(struct behavior *b, int priority, int level)
{        
  /*--- If behavior has timed out, return 1 without generating any commands */
  if (manage_time(b, bArg(9)) == 1)
    return(1);
    
  /*--- Load heading...if mode not negative.... */
  if (vvp->b[SETMODE].arg[0].x >= 0) {
          vvp->c[priority].heading_mode = (int) floor(vvp->b[SETMODE].arg[0].x + 0.5);              
          vvp->c[priority].heading[0] = vvp->b[SETMODE].arg[1].x;    
          vvp->c[priority].heading[1] = vvp->b[SETMODE].arg[2].x;    
                }          
                
  /*--- Load depth...if mode not negative....  */
  if (vvp->b[SETMODE].arg[3].x >= 0) {
          vvp->c[priority].depth_mode = (int) floor(vvp->b[SETMODE].arg[3].x + 0.5);              
          vvp->c[priority].depth[0] = vvp->b[SETMODE].arg[4].x;    
          vvp->c[priority].depth[1] = vvp->b[SETMODE].arg[5].x;    
                }          

  /*--- Load speed...if mode not negative....  */
  if (vvp->b[SETMODE].arg[6].x >= 0) {
          vvp->c[priority].speed_mode = (int) floor(vvp->b[SETMODE].arg[6].x + 0.5);              
          vvp->c[priority].speed[0] = vvp->b[SETMODE].arg[7].x;    
          vvp->c[priority].speed[1] = vvp->b[SETMODE].arg[8].x;    
                }          

  return(0);
}


/*----------------------------------------------------------------------*
  SETPOINT:   B. A. Moran, 27-Sep-1997

  This behavior sets heading, depth or pitch, and speed of the vehicle for
  a given time.  |desired_pitch| > 1e-3 (radians) overrides depth control.
  'cycles' (default 1) determines how many iterations occur, incrementing
  the heading by 'turn' (default 0) each time.  Total elapsed time for this
  behavior is the product of the arguments 'cycles' and 'time'.

 behavior: setpoint 10
  b_arg:                   heading(rad) 0
  b_arg:                       depth(m) 0
  b_arg:                     speed(m/s) 0
  b_arg:                        time(s) 0
  b_arg:                    cycles(int) 1
  b_arg:                      turn(rad) 0
  b_arg:             desired_pitch(rad) 0
 *----------------------------------------------------------------------*/

int setpoint( struct behavior *b, int priority, int level )
{
    register struct command *cmd = &vvp->c[priority];
    enum { HEAD, DEPTH, SPEED, TIME, CYCLES, TURN, PITCH };

    switch ( b->state )
    {
    case B_UNINITIALIZED:

	if ( stack_busy(cmd) )
	    return 1;
	b->state = B_ACTIVE;

    case B_ACTIVE:

	if ( manage_time(b, bArg(TIME)) == 1 )
	{
                                /* first check the remaining cycles */
	    bArg(CYCLES) = floor( bArg(CYCLES) - 1 );
	    if ( bArg(CYCLES) == 0 )
	    {
		b->state = B_COMPLETE;
		return 1;
	    }
                                /* increment the heading by 'turn' and
				   end_time by 'time' */
	    bArg(HEAD) += bArg(TURN);
	    b->end_time += bArg(TIME);
	}
                                /* load output commands */
	if ( fabs(bArg(PITCH)) < 1e-3 )
	{
	    cmd->depth_mode = 1;
	    cmd->depth[0] = bArg(DEPTH);
	}
	else
	{
	    cmd->depth_mode = 2;
	    cmd->depth[0] = bArg(PITCH);
	}

	cmd->heading_mode = 1;
	cmd->heading[0] = bArg(HEAD);    

	cmd->speed_mode = 1;
	cmd->speed[0] = bArg(SPEED);
    }
    return 0;
}

