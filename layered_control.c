/* -------------------------------------------------------------------------- 
|  SET_RUDDER:                                                                  
|   This behavior sets the vehicle rudder to a given setting and leaves it
|    there.  
|  
|  Arguments are:
|    0    "rudder(rad)", 0.000000, 0, 0, 
|    1    "depth(m)", 0.000000, 0, 0, 
|    2    "speed(m/s)", 0.000000, 0, 0, 
|    3    "time(s)", 0.000000, 0, 0,                                     
|    4    "finished(bool), 0.0, 0, 0
|                                                                            
|  J. G. Bellingham, 2/?/94                                                
|  jleonard 3/20/95 changing so that you can sequence setrudders
|  and they don't execute until they are at the top of the stack. 
  -------------------------------------------------------------------------- */

int set_rudder(struct behavior *b, int priority, int level)
{
    static const int Finished = 4;

    if (b->arg[Finished].x == 1.0) {
        return(1);
    }
    
    /* a given set_elevator will only run if it is on the top of the stack */
    if ((vvp->c[priority].speed_mode != -1) ||
        (vvp->c[priority].heading_mode != -1) ||
        (vvp->c[priority].depth_mode != -1)) return(1);
    
    
    /* check if time has elapsed */
    if (manage_time( b, bArg(3)) == 1) {
        b->arg[Finished].x = 1.0;
        return(1);
    }

    
    /*--- Load the output commands... */
    vvp->c[priority].heading_mode = 0;
    vvp->c[priority].depth_mode = 1;
    vvp->c[priority].speed_mode = 1;
    
    vvp->c[priority].heading[0] = b->arg[0].x;    
    vvp->c[priority].depth[0] = b->arg[1].x;    
    vvp->c[priority].speed[0] = b->arg[2].x;
    
    return(0);
}


/* -------------------------------------------------------------------------- 
|  SET_ELEVATOR:                                                               
|   This behavior sets the vehicle elevator to a given setting. 
|   Will shut off if m_depth is greater than max_depth or 
|   less than min_depth, or if fabs(m_pitch)>max_pitch;
|   To allow sequencing of multiple set_elevator behaviors for 
|   FAU system identification tests, it will not execute unless
|   there are no commands coming down the stack ahead of it. 
|  
|  Arguments are:
|    0    "heading(rad)", 0.000000, 0, 0, 
|    1    "elevator(rad)", 0.000000, 0, 0, 
|    2    "speed(m/s)", 0.000000, 0, 0, 
|    3    "time(s)", 0.000000, 0, 0,                                     
|    4    "max_depth(m)", 0.000000, 0, 0, 
|    5    "min_depth(m)", 0.000000, 0, 0, 
|    6    "max_pitch(rad)", 0.000000, 0, 0, 
|    7    "finished(bool), 0.0, 0, 0
|                                                                            
|  J. Leonard 1/21/95 (following JGB's set_rudder) 
  -------------------------------------------------------------------------- */

int set_elevator(struct behavior *b, int priority, int level)
{
    static const int Max_depth = 4;
    static const int Min_depth = 5;
    static const int Max_pitch = 6;
    static const int Finished = 7;
    
    
    if (b->arg[Finished].x == 1.0) {
        return(1);
    }
    
    /* a given set_elevator will only run if it is on the top of the stack */
    if ((vvp->c[priority].speed_mode != -1) ||
        (vvp->c[priority].heading_mode != -1) ||
        (vvp->c[priority].depth_mode != -1)) return(1);
    
    
    /* check if time has elapsed */
    if (manage_time( b, bArg(3)) == 1) {
        b->arg[Finished].x = 1.0;
        return(1);
    }

    /* check if depth is within limits */
    if (sensor(M_DEPTH) < b->arg[Min_depth].x) {

        b->arg[Finished].x = 1.0;
        return(1);
    }
    if (sensor(M_DEPTH) > b->arg[Max_depth].x) {
        b->arg[Finished].x = 1.0;
        return(1);
    }
    /* check if pitch is within limits */
    if (fabs(sensor(M_PITCH)) > b->arg[Max_pitch].x) {

        b->arg[Finished].x = 1.0;
        return(1);
    }
    

    /*--- Load the output commands... */
    vvp->c[priority].heading_mode = 1;
    vvp->c[priority].depth_mode = 0;
    vvp->c[priority].speed_mode = 1;
    
    vvp->c[priority].heading[0] = b->arg[0].x;    
    vvp->c[priority].depth[0] = b->arg[1].x;    
    vvp->c[priority].speed[0] = b->arg[2].x;
    
    return(0);
}

/* -------------------------------------------------------------------------- 
  DEPTH_ENVELOPE:  J. G. Bellingham Feb-1994

  This behavior prevents the vehicle from decending below the "max_depth"
  or ascending above the "min_depth".  If "alt_env_active" is > 0.0, then
  it also prevents the vehicle from approaching closer to the bottom than
  "min_altitude".  If "depth_cutoff_active" is > 0.0, then it shuts the
  vehicle down if the "cutoff_depth" is reached.
  
 behavior: depth_envelope
  b_arg:                   max_depth(m) 0
  b_arg:                   min_depth(m) 0
  b_arg:           alt_env_active(bool) 0
  b_arg:                min_altitude(m) 0
  b_arg:      depth_cutoff_active(bool) 0
  b_arg:                cutoff_depth(m) 0
  -------------------------------------------------------------------------- */

int depth_envelope( struct behavior *b, int priority, int level )
{
    register struct command *cmd = &vvp->c[priority];
    enum { D_MAX, D_MIN, ALT_ACTIVE, A_MIN, CUT_ACTIVE, CUT_MAX };

    double dummy, max_depth, min_depth;
    int alt_active, cut_active;
    
				/* make args more readable */
    max_depth = bArg(D_MAX);
    min_depth = bArg(D_MIN);
    cut_active = bArg( CUT_ACTIVE ) != 0;
    alt_active = bArg( ALT_ACTIVE ) != 0;

				/* if depth cutoff active and max depth
                                   reached, shut vehicle down */
    if ( cut_active && (sensor(M_DEPTH) > bArg(CUT_MAX)) )
    {
        sprintf( msg_buf, "% 8.2f: %s cutoff at %.1f m, exiting\n",
		 sensor(M_PRESENT_TIME), b->name, sensor(M_DEPTH) );
	write_message( MonitorLayeredControl | SLOG );

	exit_gracefully( 0 );

        return 1;
    }
				/* check minimum altitude */
    dummy = sensor( M_DEPTH ) + ( sensor(M_ALTITUDE) - bArg(A_MIN) );
    if ( alt_active && (sensor(M_ALTITUDE) > 0.0) && (dummy < bArg(D_MAX)) )
	max_depth = dummy;

				/* if already in depth mode, give new max
				   depth */

    if ( (cmd->depth_mode == 1) && (cmd->depth[0] > max_depth) )

	cmd->depth[0] = max_depth;

				/* if max depth has been exceeded, then  */
    if ( sensor(M_DEPTH) > max_depth )
    {
        if ( cmd->depth_mode == 1 )
        {
            if ( cmd->depth[0] > max_depth )
                cmd->depth[0] = max_depth;
        }
        else
	{
            cmd->depth_mode = 1;
            cmd->depth[0] = max_depth;
        }
    }

    if ( (cmd->depth[0] < min_depth) && (cmd->depth_mode == 1) )

        cmd->depth[0] = min_depth;

    return 0;
}


/*----------------------------------------------------------------------*
  LAUNCH: B. A. Moran 16-May-1997

  Command zero actuators until vehicle reaches depth or time has expired.
  Plan is to use this behavior as a trigger for the thruster to come on
  when an operator pushes down.

behavior: launch
  b_arg:                     speed(m/s) 0
  b_arg:            elevator_angle(rad) 0
  b_arg:                       depth(m) 0
  b_arg:                     timeout(s) 5
 *----------------------------------------------------------------------*/
  
int launch( struct behavior *b, int priority, int level )
{
    register struct command *cmd = &vvp->c[priority];
    enum { SPEED, ELEV, DEPTH, TIME };

    switch ( b->state )
    {
    case B_UNINITIALIZED:

	if ( stack_busy(cmd) )
	    return 0;
	b->state = B_ACTIVE;
				/* "break" intentionally omitted */
    case B_ACTIVE:

	if ( (sensor(M_DEPTH) > bArg(DEPTH)) || manage_time(b, bArg(TIME)) )
	{
	    b->state = B_COMPLETE;
	    return 1;
	}
				/* command speed & elevator angle */
	cmd->speed_mode = 1;
	cmd->speed[0] = bArg(SPEED);
	cmd->depth_mode = 0;
	cmd->depth[0] = bArg(ELEV);
				/* hold rudder straight */
	cmd->heading_mode = 0;
	cmd->heading[0] = 0.;
    }
    return 0;
}


/* ----------------------------------------------------------------
   CHIRP_FIN: B. A. Moran 26-May-1995

   Generates fin commands that follow a chirped sine wave of specified
   amplitude, linearly varying in frequency from freq_0 to freq_1 over
   specified time duration.  Set fin_name to 0 for rudder or 1 for
   elevator.

 behavior: chirp_fin
  b_arg:                   key_delay(s) 0
  b_arg:                   key_depth(m) 0
  b_arg:                 fin_name(bool) 0
  b_arg:                 amplitude(rad) 0
  b_arg:                  init_freq(hz) 0
  b_arg:                 final_freq(hz) 0
  b_arg:                    duration(s) 0
 * ---------------------------------------------------------------- */

int chirp_fin( struct behavior *b, int priority, int level )
{
    const int Delay = 0, Depth = 1, Fin_Name = 2, Amplitude = 3,
	Freq_0 = 4, Freq_1 = 5, Duration = 6;
    double freq, desired_angle, time;

    if ( sensor(M_PRESENT_TIME) < b->arg[Delay].x )
    {
         if ( b->arg[Depth].x > 0 && sensor( M_DEPTH )
             >= b->arg[Depth].x )
              b->arg[Delay].x = sensor( M_PRESENT_TIME );
         else
              return 1;
    }

    time = sensor( M_PRESENT_TIME ) - b->arg[Delay].x;

    if ( time > b->arg[Duration].x )
                                /* done if elapsed > duration */
        return 0;

    freq = b->arg[Freq_0].x + (b->arg[Freq_1].x - b->arg[Freq_0].x) *
        time / b->arg[Duration].x;

    desired_angle = b->arg[Amplitude].x * sin( 2*PI*freq*time );

                                /* Load the output commands... */
    if ( b->arg[Fin_Name].x <= 0.5 )
    {
         vvp->c[priority].heading_mode = 0;
         vvp->c[priority].heading[0] = desired_angle;
    }
    else if ( b->arg[Fin_Name].x > 0.5 )
    {
         vvp->c[priority].depth_mode = 0;
         vvp->c[priority].depth[0] = desired_angle;
    }

    return 0;
}


